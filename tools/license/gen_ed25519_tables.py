#!/usr/bin/env python3
"""Generates Source/license/Ed25519Tables.inc: the constants used by the verify-only Ed25519 / SHA-512 code.

Everything is computed from its mathematical definition (no hand-typed tables), so a typo cannot slip in:
  * SHA-512 round constants K = first 64 fractional bits of the cube roots of the first 80 primes, H0 from the square roots of the first 8.
  * Curve25519 field prime p = 2^255-19, curve constant d = -121665/121666, base point (x, y = 4/5), sqrt(-1) = 2^((p-1)/4),
    group order L = 2^252 + 27742317777372353535851937790883648493.
Run:  python3 tools/license/gen_ed25519_tables.py > Source/license/Ed25519Tables.inc
"""
import sys
from math import isqrt


def icbrt(n):
    lo, hi = 0, 1 << ((n.bit_length() // 3) + 2)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if mid ** 3 <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


def primes(count):
    out, n = [], 2
    while len(out) < count:
        if all(n % q for q in out if q * q <= n):
            out.append(n)
        n += 1
    return out


P = 2 ** 255 - 19
L = 2 ** 252 + 27742317777372353535851937790883648493
D = (-121665 * pow(121666, P - 2, P)) % P
SQRTM1 = pow(2, (P - 1) // 4, P)


def recover_x(y, sign):
    x2 = (y * y - 1) * pow(D * y * y + 1, P - 2, P) % P
    x = pow(x2, (P + 3) // 8, P)
    if (x * x - x2) % P != 0:
        x = x * SQRTM1 % P
    assert (x * x - x2) % P == 0
    if x & 1 != sign:
        x = P - x
    return x


BY = 4 * pow(5, P - 2, P) % P
BX = recover_x(BY, 0)


def le32(v):
    return v.to_bytes(32, "little")


def carr(name, data):
    return "static const unsigned char %s[%d] = {%s};" % (name, len(data), ",".join("0x%02x" % b for b in data))


def main():
    out = ["// GENERATED by tools/license/gen_ed25519_tables.py - do not edit by hand."]
    ps = primes(80)
    k = [icbrt(q << 192) & (2 ** 64 - 1) for q in ps]
    h0 = [isqrt(q << 128) & (2 ** 64 - 1) for q in ps[:8]]
    out.append("static const unsigned long long kSha512K[80] = {" + ",".join("0x%016xULL" % v for v in k) + "};")
    out.append("static const unsigned long long kSha512H0[8] = {" + ",".join("0x%016xULL" % v for v in h0) + "};")
    out.append(carr("kBytesD", le32(D)))
    out.append(carr("kBytesD2", le32(2 * D % P)))
    out.append(carr("kBytesBaseX", le32(BX)))
    out.append(carr("kBytesBaseY", le32(BY)))
    out.append(carr("kBytesSqrtM1", le32(SQRTM1)))
    out.append(carr("kBytesL", le32(L)))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
